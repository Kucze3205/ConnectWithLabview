#!/usr/bin/env python3
"""Generate public, deterministic development challenge fixtures.

This is preparation data, not a scorer. It reads only the checked-in public case
inventories and emits deliberately small submissions plus independently stated
expectations. --check compares regenerated bytes without writing.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASE_DIR = ROOT / "benchmark" / "cases" / "dev"
OUT_DIR = ROOT / "benchmark" / "challenges"
CASES = ("class-stop-msg", "library-framework", "vi-actor-core-native-gap")


def load_case(case_id):
    with (CASE_DIR / (case_id + ".json")).open(encoding="utf-8") as f:
        return json.load(f)


def first_claims(case, n=2):
    rows = [x for x in case["reference_inventory"] if x.get("claim_id", "").startswith("A")]
    result = []
    for row in rows[:n]:
        cite = dict(row["citations"][0]) if row.get("citations") else {}
        result.append({"claim_id": row["claim_id"], "answer": row["atomic_fact"].get("value"),
                       "conditions": list(row.get("conditions", [])), "citations": [cite] if cite else []})
    return result


def ids(case, dimension):
    return list(case["denominators"][dimension]["required_ids"])


def base(case, challenge_id, label):
    return {
        "schema_version": 1,
        "fixture_id": challenge_id,
        "label": label,
        "source": {"case_id": case["case_id"], "case_revision": case["case_revision"],
                   "family": case["family"], "save_version": case["save_version"],
                   "artifact": case["artifact"]},
        "public_development_only": True,
        "submitted": {"answer_record": {"case_id": case["case_id"], "status": "complete",
                         "claims": first_claims(case), "limitations": ""},
                       "reader_response": {"probe_id": case["reader_probe_contract"]["probe_id"],
                         "status": "not-executed", "observations": [], "limitations": ""}},
        "denominators": {k: case["denominators"][k]["count"] for k in
                         ("answer_correctness", "source_grounding", "reading_fidelity")},
        "expected": {"dimensions": {}, "extras_ledger": [], "duplicates": [], "contradictions": []},
        "evidence_status": "independently derived from public provisional inventory; native evidence unavailable",
    }


def expected(dimensions, extras=None, duplicates=None, contradictions=None):
    return {"dimensions": dimensions, "extras_ledger": extras or [],
            "duplicates": duplicates or [], "contradictions": contradictions or []}


def make_fixtures():
    cases = {c: load_case(c) for c in CASES}
    out = {}
    c = cases["class-stop-msg"]
    f = base(c, "class-stop-msg-positive-and-answer-errors", "positive controls and answer/citation mutations")
    a = ids(c, "answer_correctness")
    f["expected"] = expected({"correctness": "correct", "grounding": "correct", "fidelity": "unsupported"})
    f["controls"] = [{"name": "positive-control", "mutation": "none", "expected": {"correctness": "correct", "grounding": "correct"}},
                     {"name": "wrong-answer", "mutation": {"claim_id": a[0], "replace_answer": "DELIBERATELY-WRONG-LITERAL", "retain_locator": True},
                      "expected": {"correctness": "incorrect", "grounding": "correct"}},
                     {"name": "wrong-citation-existing", "mutation": {"claim_id": a[0], "use_locator_from": a[1]},
                      "expected": {"correctness": "correct", "grounding": "incorrect"}},
                     {"name": "wrong-citation-unresolvable", "mutation": {"claim_id": a[0], "locator": "/does/not/resolve"},
                      "expected": {"correctness": "correct", "grounding": "incorrect"}}]
    out[f["fixture_id"]] = f

    c = cases["library-framework"]
    f = base(c, "library-framework-accounting", "omissions, extras, duplicates, contradictions and probe failures")
    a = ids(c, "answer_correctness"); r = ids(c, "reading_fidelity")
    f["controls"] = [
      {"name": "selective-omission-answer", "mutation": {"remove_claim_id": a[1]}, "expected": {"correctness": "partial", "grounding": "partial"}},
      {"name": "selective-omission-reader", "mutation": {"remove_observation_id": r[1]}, "expected": {"fidelity": "partial"}},
      {"name": "extra-false-answer", "mutation": {"extra": "false assertion", "citation": "existing-non-supporting"}, "expected": {"correctness": "incorrect", "grounding": "incorrect"}},
      {"name": "extra-true", "mutation": {"extra": "true but not required assertion"}, "expected": {"correctness": "correct", "grounding": "correct"}},
      {"name": "extra-unverified-reader", "mutation": {"extra": "unverified observation"}, "expected": {"fidelity": "unverified"}},
      {"name": "duplicate", "mutation": {"repeat_claim_id": a[0]}, "expected": {"correctness": "correct", "duplicate_count": 1}},
      {"name": "contradiction", "mutation": {"negate_claim_id": a[0], "retain_original": True}, "expected": {"correctness": "incorrect", "grounding": "incorrect", "contradiction_count": 1}},
      {"name": "empty-probe", "mutation": {"reader_response": ""}, "expected": {"fidelity": "missing"}},
      {"name": "truncated-probe", "mutation": {"reader_response": "prefix-only", "truncated": True}, "expected": {"fidelity": "missing"}},
      {"name": "failed-probe", "mutation": {"reader_error": "controlled reader error", "executed": False}, "expected": {"fidelity": "error"}},
      {"name": "unsupported-probe", "mutation": {"status": "unsupported", "reason": "missing runtime/dependency/license"}, "expected": {"fidelity": "unsupported"}},
      {"name": "missing-key-zero-tests", "mutation": {"independent_key": None, "executed_tests": 0}, "expected": {"correctness": "unverified", "grounding": "unverified", "fidelity": "unverified"}},
    ]
    f["expected"] = expected({"correctness": "correct", "grounding": "correct", "fidelity": "unsupported"})
    out[f["fixture_id"]] = f

    c = cases["vi-actor-core-native-gap"]
    f = base(c, "vi-actor-core-native-gap", "unsupported/native-gap row and constant-export comparison")
    f["submitted"]["answer_record"]["status"] = "unsupported"
    f["submitted"]["answer_record"]["limitations"] = "Native connector, diagram and controlled behavior evidence unavailable."
    f["submitted"]["reader_response"]["status"] = "unsupported"
    f["expected"] = expected({"correctness": "unsupported", "grounding": "unsupported", "fidelity": "unsupported"})
    f["controls"] = [{"name": "unsupported-case", "mutation": {"declared_limitation": True},
                      "expected": {"correctness": "unsupported", "grounding": "unsupported", "fidelity": "unsupported"}},
                     {"name": "constant-export", "mutation": {"export": "same-plausible-export", "compared_cases": ["class-stop-msg", "library-framework"],
                         "incompatible_facts": "case-specific required observations differ"},
                      "expected": {"fidelity": "incorrect", "comparison_required": True}}]
    f["gaps"] = [{"id": x, "status": "explicit-gap", "reason": "native evidence and controlled fixture unavailable"}
                  for x in ids(c, "answer_correctness")]
    out[f["fixture_id"]] = f
    return out


def rendered():
    result = make_fixtures()
    return {k + ".json": json.dumps(v, indent=2, sort_keys=True, ensure_ascii=False) + "\n" for k, v in result.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = rendered()
    if args.check:
        actual = {p.name: p.read_text(encoding="utf-8") for p in OUT_DIR.glob("*.json")}
        if actual != files:
            missing = sorted(set(files) - set(actual)); extra = sorted(set(actual) - set(files))
            raise SystemExit("challenge bytes differ (missing=%s extra=%s)" % (missing, extra))
        print("challenge fixtures match")
        return
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    print("wrote %d challenge fixtures" % len(files))

if __name__ == "__main__":
    main()
